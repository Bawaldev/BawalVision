from bing_image_downloader import downloader
import os

queries = {
    "tofu": [
        "raw white tofu block",
        "fried tofu cubes",
        "pan fried tofu slices",
        "cooked brown tofu"
    ]
}

base_dir = "dataset_mbg_matang"
limit_per_query = 100

for category, search_terms in queries.items():
    category_dir = os.path.join(base_dir, category)

    for term in search_terms:
        downloader.download(
            term,
            limit=limit_per_query,
            output_dir=category_dir,
            adult_filter_off=False,
            force_replace=False,
            timeout=10,
            verbose=True
        )

import os
import shutil

source_dir = "dataset_mbg_matang"
output_dir = "dataset_tofu_flat"
os.makedirs(output_dir, exist_ok=True)

counter = 1
for root, dirs, files in os.walk(source_dir):
    for file in files:
        if file.lower().endswith(('.png', '.jpg', '.jpeg', '.webp')):
            ext = os.path.splitext(file)[1].lower()
            old_path = os.path.join(root, file)
            new_path = os.path.join(output_dir, f"{counter}{ext}")

            shutil.copy(old_path, new_path)
            counter += 1

print(f"Total gambar yang diproses dan diubah namanya: {counter - 1}")

