#!/usr/bin/env python3
"""
Generate and maintain a secure .env file for BawalVision.
Zero secrets in repository: generates cryptographically secure random tokens
for device authentication, admin API, AWS Lambda auth, PostgreSQL, and Grafana.
"""

import os
import secrets
import stat
import string
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT_DIR / ".env"
ENV_EXAMPLE = ROOT_DIR / ".env.example"

def generate_alphanumeric_password(length: int = 24) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))

def generate_hex_token(bytes_count: int = 16) -> str:
    return secrets.token_hex(bytes_count)

SECRET_CONFIG = {
    "BAWAL_DEVICE_TOKEN": lambda: generate_hex_token(16),
    "BAWAL_ADMIN_TOKEN": lambda: generate_hex_token(16),
    "BAWAL_LAMBDA_AUTH_TOKEN": lambda: generate_hex_token(16),
    "RELAY_INGEST_KEY": lambda: generate_hex_token(24),
    "POSTGRES_PASSWORD": lambda: generate_alphanumeric_password(24),
    "GRAFANA_ADMIN_PASSWORD": lambda: generate_alphanumeric_password(24),
}

def parse_env_file(path: Path) -> dict:
    if not path.is_file():
        return {}
    entries = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, val = line.split("=", 1)
                entries[key.strip()] = val.strip()
    return entries

def is_placeholder(val: str) -> bool:
    if not val:
        return True
    val_clean = val.strip().strip("'\"")
    if not val_clean:
        return True
    if val_clean.startswith("<") and val_clean.endswith(">"):
        return True
    # Known legacy insecure default passwords
    if val_clean.lower() in ("postgres", "admin", "password", "bawal_secure_token_prod"):
        return True
    return False

def main() -> int:
    created = False
    updated_keys = []

    lines = []
    if ENV_FILE.is_file():
        with open(ENV_FILE, "r", encoding="utf-8") as f:
            lines = f.readlines()
    elif ENV_EXAMPLE.is_file():
        with open(ENV_EXAMPLE, "r", encoding="utf-8") as f:
            lines = f.readlines()
        created = True
    else:
        print("[ERROR] .env.example not found!", file=sys.stderr)
        return 1

    current_env = parse_env_file(ENV_FILE) if ENV_FILE.is_file() else {}

    # Update or add missing secret keys
    new_lines = []
    seen_keys = set()

    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key, val = stripped.split("=", 1)
            key = key.strip()
            val = val.strip()
            seen_keys.add(key)
            if key in SECRET_CONFIG:
                existing_val = current_env.get(key, val)
                if is_placeholder(existing_val):
                    generated_val = SECRET_CONFIG[key]()
                    new_lines.append(f"{key}={generated_val}\n")
                    updated_keys.append(key)
                else:
                    new_lines.append(f"{key}={existing_val}\n")
            else:
                new_lines.append(line)
        else:
            new_lines.append(line)

    # Append any secret keys that weren't in the template
    missing_secrets = [k for k in SECRET_CONFIG if k not in seen_keys]
    if missing_secrets:
        new_lines.append("\n# Security & Auth Secrets (Generated by `just setup`)\n")
        for key in missing_secrets:
            generated_val = SECRET_CONFIG[key]()
            new_lines.append(f"{key}={generated_val}\n")
            updated_keys.append(key)

    with open(ENV_FILE, "w", encoding="utf-8") as f:
        f.writelines(new_lines)

    # Restrict permissions to 0600 (read/write only by owner)
    try:
        os.chmod(ENV_FILE, stat.S_IRUSR | stat.S_IWUSR)
    except Exception:
        pass

    if created:
        print(f"[SUCCESS] Created {ENV_FILE.name} from template with 0600 permissions.")
    if updated_keys:
        print(f"[SUCCESS] Generated secure random secrets for: {', '.join(updated_keys)}")
    else:
        print("[INFO] .env already contains all required secrets.")

    return 0

if __name__ == "__main__":
    sys.exit(main())

